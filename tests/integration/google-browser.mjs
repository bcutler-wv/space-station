  assert.deepEqual(afterReconnect, original, 'reconnect must retain account ID, Orbit and backfill');
  await page.goto(returnUrl);
  await page.getByText(/No pending Google return was found/).waitFor();
  assert.equal((await (await page.request.get(`${origin}/fixture/observations`)).json()).providerCalls, 6, 'reconnect replay must not call provider');
  await page.goto(`${origin}/setup/google`);
  await page.getByLabel('Web client ID').fill(clientId);
  await page.getByLabel('Web client secret').fill(clientSecret);
  await page.route('https://accounts.google.com/**', async (route) => {
    const state = new URL(route.request().url()).searchParams.get('state');
    await route.fulfill({ status: 200, contentType: 'text/html', body: `<html><body><a href="${redirect}?state=${encodeURIComponent(state)}&error=access_denied">Cancel fixture consent</a></body></html>` });
  });
  await page.getByRole('button', { name: 'Continue to Google' }).click();
  await page.getByRole('link', { name: 'Cancel fixture consent' }).click();
