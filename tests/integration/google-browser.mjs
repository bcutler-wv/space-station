import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import { generate } from 'otplib';
import process from 'node:process';
import { URL } from 'node:url';

const origin = process.env.STATION_GOOGLE_BROWSER_BASE_URL;
const tokenPath = process.env.STATION_GOOGLE_BROWSER_BOOTSTRAP_PATH;
if (!origin || !tokenPath) throw new Error('Google browser fixture origin and token path are required.');
const browser = await chromium.launch();
const clientId = '123456-fixture.apps.googleusercontent.com';
const clientSecret = 'fixture-client-secret';
const capture = async (page, label) => { await mkdir('test-results/google-browser', { recursive: true }); await page.screenshot({ path: `test-results/google-browser/${label}.png`, fullPage: true }); };
try {
  const context = await browser.newContext({ ignoreHTTPSErrors: true, colorScheme: 'light' });
  const page = await context.newPage();
  await page.goto(origin);
  await page.getByRole('heading', { name: 'Create your login' }).waitFor();
  await page.getByLabel('One-time setup token').fill((await readFile(tokenPath, 'utf8')).trim());
  await page.getByLabel('Your name').fill('Example Owner');
  await page.getByLabel('Password', { exact: true }).fill('Example-only-password-123!');
  await page.getByRole('button', { name: 'Create password login' }).click();
  await page.getByRole('heading', { name: 'Connect your authenticator' }).waitFor();
  const secret = new URL(await page.getByLabel('Authenticator setup URI').inputValue()).searchParams.get('secret');
  assert.ok(secret);
  await page.getByLabel('Six-digit code').fill(await generate({ secret }));
  await page.getByRole('button', { name: 'Confirm code' }).click();
  await page.getByRole('button', { name: 'I saved my codes' }).click();
  await page.goto(`${origin}/setup`);
  await page.getByRole('heading', { name: 'Set up your first Orbit' }).waitFor();
  await page.getByLabel('I confirm this is the address I will use').check();
  await page.getByLabel('Orbit name').fill('Example work');
  await page.getByLabel('What is this part of your work?').fill('Example only');
  await page.getByRole('group', { name: 'Global' }).getByLabel('Search indexing').selectOption('exclude');
  await page.getByRole('group', { name: 'Global' }).getByLabel('AI processing').selectOption('exclude');
  await page.getByRole('group', { name: 'First Orbit' }).getByLabel('Search indexing').selectOption('exclude');
  await page.getByRole('group', { name: 'First Orbit' }).getByLabel('AI processing').selectOption('exclude');
  await page.getByRole('button', { name: 'Save Orbit and privacy choices' }).click();
  await page.getByRole('link', { name: 'Connect Google mail' }).click();
  await page.getByRole('heading', { name: 'Connect Google mail' }).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  const redirect = await page.getByLabel('Authorized redirect URI').inputValue();
  assert.equal(redirect, `${origin}/api/google/callback`);
  assert.equal(await page.getByLabel('Gmail scope').inputValue(), 'https://www.googleapis.com/auth/gmail.modify');
  await capture(page, 'guided-light');
  let returnUrl = '';
  await page.route('https://accounts.google.com/**', async (route) => {
    const authorize = new URL(route.request().url());
    const state = authorize.searchParams.get('state');
    assert.ok(state);
    assert.equal(authorize.searchParams.get('code_challenge_method'), 'S256');
    assert.equal(authorize.searchParams.get('redirect_uri'), redirect);
    returnUrl = `${redirect}?state=${encodeURIComponent(state)}&code=fixture-code`;
    await route.fulfill({ status: 200, contentType: 'text/html', body: `<html><body><h1>Fixture consent</h1><a href="${returnUrl}">Approve example.com account</a></body></html>` });
  });
  await page.getByLabel('Web client ID').fill(clientId);
  await page.getByLabel('Web client secret').fill(clientSecret);
  await page.getByRole('button', { name: 'Continue to Google' }).click();
  await page.getByRole('heading', { name: 'Fixture consent' }).waitFor();
  assert.ok(page.url().startsWith('https://accounts.google.com/'));
  await page.getByRole('link', { name: 'Approve example.com account' }).click();
  await page.getByRole('heading', { name: 'Finish Google connection' }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/setup/google/continue');
  assert.equal(new URL(page.url()).search, '');
  assert.equal(await page.evaluate(() => JSON.stringify([Object.entries(globalThis.localStorage), Object.entries(globalThis.sessionStorage)]).includes('fixture-code')), false);
  const observation = await (await page.request.get(`${origin}/fixture/observations`)).json();
  assert.deepEqual(observation.callbackCookies, [false], 'Strict cookie must be omitted on cross-site callback');
  assert.equal(observation.providerCalls, 0, 'provider exchange must await explicit confirmation');
  const otherContext = await browser.newContext({ ignoreHTTPSErrors: true });
  const otherPage = await otherContext.newPage();
  await otherPage.goto(`${origin}/setup/google/continue`);
  await otherPage.getByRole('heading', { name: 'Sign in' }).waitFor();
  assert.equal((await (await otherPage.request.get(`${origin}/fixture/observations`)).json()).providerCalls, 0, 'another browser cannot confirm');
  await otherContext.close();
  await page.reload();
  await page.getByRole('button', { name: 'Confirm Google connection' }).waitFor();
  await capture(page, 'continuation-light');
  await page.getByRole('button', { name: 'Confirm Google connection' }).click();
  await page.getByRole('status').getByText('Account connected').waitFor();
  await page.getByRole('link', { name: 'Choose a backfill window' }).click();
  await page.getByRole('heading', { name: 'owner@example.com' }).waitFor();
  await page.getByLabel('1 year').check();
  await page.getByRole('button', { name: 'Save backfill choice' }).click();
  await page.getByText('Backfill choice: 1 year. Mail sync is pending implementation.').waitFor();
  await page.reload();
  await page.getByText('Backfill choice: 1 year. Mail sync is pending implementation.').waitFor();
  assert.equal((await (await page.request.get(`${origin}/fixture/observations`)).json()).providerCalls, 2);
  await page.goto(returnUrl);
  await page.getByText(/No pending Google return was found/).waitFor();
  assert.equal((await (await page.request.get(`${origin}/fixture/observations`)).json()).providerCalls, 2, 'replay must not exchange again');
  await page.goto(`${origin}/setup/google`);
  await page.getByLabel('Web client ID').fill(clientId);
  await page.getByLabel('Web client secret').fill(clientSecret);
  await page.route('https://accounts.google.com/**', async (route) => {
    const state = new URL(route.request().url()).searchParams.get('state');
    await route.fulfill({ status: 200, contentType: 'text/html', body: `<html><body><a href="${redirect}?state=${encodeURIComponent(state)}&error=access_denied">Cancel fixture consent</a></body></html>` });
  });
  await page.getByRole('button', { name: 'Continue to Google' }).click();
  await page.getByRole('link', { name: 'Cancel fixture consent' }).click();
  await page.getByText(/No pending Google return was found/).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.goto(`${origin}/setup/google`);
  await page.getByRole('heading', { name: 'Connect Google mail' }).waitFor();
  await page.waitForFunction(() => globalThis.document.documentElement.dataset.theme === 'dark');
  assert.equal(await page.evaluate(() => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth), true, 'mobile page must not scroll horizontally');
  await capture(page, 'connected-mobile-dark');
  await page.goto(`${origin}/setup/google/continue`);
  await page.getByText(/No pending Google return was found/).waitFor();
  assert.equal(new URL(page.url()).search, '');
  process.stdout.write('HTTPS Google browser connection, Strict-cookie continuation, backfill, replay, cancellation, mobile and theme checks passed.\n');
  await context.close();
} finally { await browser.close(); }
