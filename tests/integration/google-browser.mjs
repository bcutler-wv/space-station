  assert.deepEqual(afterWrong, original, 'wrong mailbox must leave account metadata unchanged');
  await page.goto(returnUrl);
  await page.getByText(/No pending Google return was found/).waitFor();
  assert.equal((await (await page.request.get(`${origin}/fixture/observations`)).json()).providerCalls, 4, 'wrong mailbox replay must not call provider');
