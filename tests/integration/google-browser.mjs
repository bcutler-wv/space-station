  authorizationCode = 'fixture-reconnect-code';
  await page.getByRole('button', { name: 'Reconnect owner@example.com' }).click();
  await page.getByLabel('Web client ID').fill(clientId);
  await page.getByLabel('Web client secret').fill(clientSecret);
  await page.getByRole('button', { name: 'Continue to Google for owner@example.com' }).click();
  await page.getByRole('link', { name: 'Approve example.com account' }).click();
  await page.getByRole('button', { name: 'Confirm Google reconnect' }).click();
