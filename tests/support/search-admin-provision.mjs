import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import console from 'node:console';
import { randomBytes } from 'node:crypto';
import { lstat, open } from 'node:fs/promises';
import process from 'node:process';
import { clearTimeout, setTimeout } from 'node:timers';
import { readSearchAdminPassword } from '../../packages/db/dist/index.js';

const mode = process.argv[2];
assert.ok(mode === 'local' || mode === 'container');
const root = process.env.SEARCH_ADMIN_TEST_SECRET_ROOT;
const localHost = process.env.SEARCH_ADMIN_TEST_OWNER_HOST ?? `${process.cwd()}/.cache/results`;
const localPort = process.env.SEARCH_ADMIN_TEST_PORT ?? '55433';
assert.ok(root?.startsWith(`${process.cwd()}/.cache/results/`) && !root.includes('..'));
const roles = [
  ['station_search_verifier', 'verifier'],
  ['station_search_transition', 'transition'],
];

async function psql(args, input = '') {
  const command = mode === 'local' ? 'psql' : 'docker';
  const prefix = mode === 'local' ? [] : ['exec', '-i', 'station-search-admin-pg16', 'psql'];
  const env = mode === 'local' ? { PATH: process.env.PATH,
    PGHOST: localHost, PGPORT: localPort, PGUSER: 'station', PGDATABASE: 'station' } : process.env;
  const child = spawn(command, [...prefix, '-X', '-U', 'station', '-v', 'ON_ERROR_STOP=1', '-d', 'station', ...args],
    { env, stdio: ['pipe', 'pipe', 'pipe'] });
  let outputBytes = 0;
  for (const stream of [child.stdout, child.stderr]) stream.on('data', chunk => {
    outputBytes += chunk.length;
    if (outputBytes > 4096) child.kill();
  });
  const timer = setTimeout(() => child.kill(), 10_000);
  child.stdin.end(input);
  const status = await new Promise((resolve, reject) => {
    child.on('error', reject); child.on('exit', resolve);
  });
  clearTimeout(timer);
  if (status !== 0 || outputBytes > 4096) throw new Error('Fixture owner psql operation failed');
}

try {
  const dir = await lstat(root);
  assert.ok(dir.isDirectory() && dir.uid === process.getuid() && (dir.mode & 0o777) === 0o700,
    'Fixture secret directory must be private and owned');
  for (const [role, name] of roles) {
    const path = `${root}/${name}.password`;
    const secret = randomBytes(32).toString('base64url');
    const file = await open(path, 'wx', 0o600);
    try { await file.writeFile(secret); } finally { await file.close(); }
    assert.ok((await readSearchAdminPassword(path)) === secret &&
      process.env.SEARCH_ADMIN_TEST_FORCE_READBACK_MISMATCH !== '1', 'Secret readback mismatch');
    // Official psql \password computes SCRAM without cleartext SQL or history.
    // Generated bytes reach only the child's stdin, never argv/env/logs.
    await psql(['-c', `\\password ${role}`], `${secret}\n${secret}\n`);
    await psql(['-c', `ALTER ROLE ${role} LOGIN`]);
  }
  console.info('Disposable restricted-role SCRAM credentials prepared privately.');
} catch {
  console.error('Disposable restricted-role credential setup failed.');
  process.exitCode = 1;
}
